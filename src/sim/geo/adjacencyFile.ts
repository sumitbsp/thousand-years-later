// The text of the generated data/earthAdjacency.ts, shared by `npm run earth`
// and the test that checks the committed file is up to date.

export function formatAdjacency(pairs: readonly (readonly [string, string])[]): string {
  const lines = pairs.map(([a, b]) => `  ['${a}', '${b}'],`);
  return `// Generated by \`npm run earth\` (scripts/buildEarth.ts) from earthRegions.ts. Do not edit.
// Pairs of region ids whose shapes touch: land–land, land–sea and sea–sea.
// Continents and straits are applied on top in src/sim/earth.ts.

export const EARTH_TOUCHING: readonly (readonly [string, string])[] = [
${lines.join('\n')}
];
`;
}
